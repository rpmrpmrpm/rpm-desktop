using System.Globalization;
using RPM.Core.Analysis;

namespace RPM.Core.Tests;

/// <summary>
/// Holds the C# log-mel against one built by the beat model's own preprocessing.
///
/// <para>This is the test the model depends on. Everything downstream of the spectrogram, the
/// beats, the bar lines, the tempo a mix is pulled to, is the model's reading of these numbers,
/// and a spectrogram that is subtly wrong does not fail: it returns a worse grid, silently, on
/// every record. A window built symmetric instead of periodic, a filter bank normalised by band
/// width, a magnitude scaled by the wrong constant: each is invisible on a plot and each is caught
/// here.</para>
///
/// <para>Assets/mel-reference.txt is generated by scripts/make_mel_reference.py (see
/// scripts/export_beat_this_onnx.py for the venv it needs) from the signal built below, which is a
/// formula rather than a recording so both sides can produce it exactly.</para>
/// </summary>
public class MelSpectrogramTests
{
    /// <summary>The signal both sides build: three tones spanning the range the filters cover, plus
    /// two clicks, which are what a beat model is actually looking at.</summary>
    private static float[] TestSignal()
    {
        const int n = MelSpectrogram.SampleRate;   // one second
        var x = new float[n];
        for (int i = 0; i < n; i++)
        {
            double t = 2 * Math.PI * i / MelSpectrogram.SampleRate;
            x[i] = (float)(0.5 * Math.Sin(440 * t) + 0.3 * Math.Sin(97 * t) + 0.2 * Math.Sin(3000 * t));
        }
        x[5000] += 0.9f;
        x[11000] += 0.9f;
        return x;
    }

    private static float[][] Reference()
    {
        var path = Path.Combine(AppContext.BaseDirectory, "Assets", "mel-reference.txt");
        return File.ReadAllLines(path)
            .Where(line => !line.StartsWith('#') && line.Length > 0)
            .Select(line => line.Split(' ').Select(v => float.Parse(v, CultureInfo.InvariantCulture)).ToArray())
            .ToArray();
    }

    [Fact]
    public void Matches_the_models_own_preprocessing()
    {
        var reference = Reference();
        var mel = MelSpectrogram.Compute(TestSignal());

        Assert.Equal(reference.Length, mel.Length);

        double worst = 0;
        var worstAt = (frame: 0, band: 0);
        var drifts = new List<double>(reference.Length * MelSpectrogram.MelBands);
        for (int f = 0; f < reference.Length; f++)
        {
            Assert.Equal(MelSpectrogram.MelBands, mel[f].Length);
            for (int b = 0; b < MelSpectrogram.MelBands; b++)
            {
                double drift = Math.Abs(reference[f][b] - mel[f][b]);
                drifts.Add(drift);
                if (drift > worst)
                {
                    worst = drift;
                    worstAt = (f, b);
                }
            }
        }

        drifts.Sort();
        double median = drifts[drifts.Count / 2];

        // Exact equality is not on offer: the reference is computed in float32 and this in float64,
        // and the two sum a thousand bins in a different order. The size of that disagreement was
        // measured: an independent float64 implementation differs from the
        // reference by 4.2e-4 at worst and 8.8e-6 typically, so the C# cannot do better and these
        // bounds sit an order of magnitude above it.
        //
        // The typical drift is the number that discriminates, which is why it is checked as well as
        // the worst. Measured against each mistake this test exists to catch, on this same signal:
        // a symmetric window moves the median to 1.2e-3, the htk mel scale to 7.0e-2, band-width
        // normalisation to 9.2e-2, and dropping the magnitude scaling to 1.3. The nearest of those
        // is still more than ten times the bound below.
        Assert.True(worst < 5e-3, $"largest drift {worst:E3} at frame {worstAt.frame}, band {worstAt.band}");
        Assert.True(median < 1e-4, $"typical drift {median:E3} is too large to be rounding");
    }

    [Fact]
    public void Frame_count_follows_the_hop()
    {
        // Centred frames: one per hop, plus the one centred on the very first sample.
        Assert.Equal(51, MelSpectrogram.FrameCount(MelSpectrogram.SampleRate));
        Assert.Equal(0, MelSpectrogram.FrameCount(0));
        Assert.Equal(MelSpectrogram.FrameCount(44100), MelSpectrogram.Compute(new float[44100]).Length);
    }

    [Fact]
    public void Fifty_frames_a_second()
    {
        Assert.Equal(50, MelSpectrogram.FrameRate, 6);
    }

    [Fact]
    public void Short_signals_do_not_throw()
    {
        // A window is 1024 samples and a track can be shorter than that; the reflection has to fold
        // repeatedly rather than run off the end.
        foreach (int length in (int[])[0, 1, 2, 17, 441, 1023])
        {
            var mel = MelSpectrogram.Compute(new float[length]);
            Assert.Equal(MelSpectrogram.FrameCount(length), mel.Length);
        }
    }

    [Fact]
    public void A_tone_lands_in_the_band_that_covers_it()
    {
        // Sanity on the filter bank's placement rather than its shape: a 440 Hz tone must peak in a
        // band whose centre is near 440 Hz, which catches a mel scale mixed up with the htk one.
        const int n = MelSpectrogram.SampleRate;
        var tone = new float[n];
        for (int i = 0; i < n; i++)
            tone[i] = (float)Math.Sin(2 * Math.PI * 440 * i / MelSpectrogram.SampleRate);

        var mel = MelSpectrogram.Compute(tone);
        var middle = mel[mel.Length / 2];
        int peak = Array.IndexOf(middle, middle.Max());

        // The Slaney scale is linear below 1 kHz, so the bottom of the range is not stretched the
        // way the htk scale stretches it: 30 Hz to 11 kHz spans about 49 mels, of which 440 Hz sits
        // 6.6 in, an eighth of the way up, band 16 of 128. On the htk scale the same tone would
        // land near band 30, which is what this is really checking.
        Assert.InRange(peak, 13, 19);
    }
}
