using System.Text.RegularExpressions;
using Windows.Storage;

namespace RPM.Desktop.Presentation.About;

/// <summary>One licence. <see cref="File"/> is a file name under Assets/Licenses. It is null when the
/// licence is a published set of terms that only its publisher may host. The screen then offers a link
/// only.</summary>
/// <param name="IsNotices">True for a notices document that covers many licences, not one licence. It holds
/// the texts that some parts of a native library require to be shipped with the app. It is hundreds of
/// kilobytes in size. It is shipped as <see cref="File"/>, but the screen sends the reader to
/// <see cref="Url"/> instead of showing it, because it is too long for one block of text in a
/// dialog.</param>
public sealed record CreditLicense(string Name, string? File, string? Url, bool IsNotices = false);

/// <summary>
/// One thing rpm ships or asks.
/// </summary>
/// <param name="Detail">What this entry is for, when the name alone does not say. For example, the shelf
/// that a photograph is shown on. This is not a string key. It is a genre's own name, taken from the same
/// table that the wall reads.</param>
/// <param name="Source">Where the source code can be obtained. It is set only where a licence requires a
/// written offer of the source. So it is not always the project link.</param>
/// <param name="UseKey">A key in the string table that says what RPM uses this entry for. It is null in the
/// generated lists, where the section's own note says this once.</param>
/// <param name="TermsUrl">The address of the terms. It is used for an entry under "Terms" whose licence has
/// no address of its own.</param>
public sealed record CreditEntry(
    string Name,
    string? Version,
    string? Detail,
    string? Copyright,
    string? Url,
    string? Source,
    string? UseKey,
    string? TermsUrl,
    IReadOnlyList<string> Licenses);

/// <param name="NoteKey">One sentence about the whole section. It is used when the entries need a statement
/// that none of them could carry alone. For example: that the typefaces are not shipped, or that the
/// catalogues' data is not included.</param>
public sealed record CreditSection(
    string TitleKey,
    string? NoteKey,
    IReadOnlyList<CreditEntry> Entries);

/// <summary>
/// The acknowledgements: what RPM ships that someone else made, and what it asks for.
///
/// <para>The lists are in Credits.Data.cs. That file is generated by scripts/gen_credits.py from
/// scripts/credits.json, so change the source file and run the script again. This file holds what the
/// generated table cannot hold: the licence texts, which are files and not strings, and the rule for
/// reading them.</para>
/// </summary>
public static partial class Credits
{
    /// <summary>Licence texts that have been read, by file name. A licence is read from disk only once.
    /// Opening the same licence again does not read the file again.</summary>
    private static readonly Dictionary<string, string> Read = [];

    /// <summary>
    /// A licence's text, with the holder's own copyright line in it.
    ///
    /// <para>The texts are the licences as published. So the permissive ones carry a placeholder line
    /// rather than a name: MIT's "Copyright (c) &lt;year&gt; &lt;copyright holders&gt;". The text is filled
    /// in because a licence that names nobody grants nothing.</para>
    ///
    /// <para>The replacement is kept narrow. Only a line whose copyright is in ANGLE BRACKETS is changed.
    /// That is the form the placeholder takes. Apache and the GPL licences have an appendix that shows how
    /// to apply the licence to your own work. Its example line uses square brackets ("Copyright [yyyy]
    /// [name of copyright owner]"). That appendix is part of the licence, so it must stay exactly as it is.
    /// HarfBuzz's text lists its real holders, and those are not placeholders either.</para>
    ///
    /// <para>If an entry has no copyright of its own, the placeholder line is removed. A line of angle
    /// brackets on screen looks like a fault in the app.</para>
    /// </summary>
    public static async Task<string> TextAsync(CreditLicense licence, string? copyright)
    {
        if (licence.File is not { } name)
            return string.Empty;

        if (!Read.TryGetValue(name, out var text))
        {
            var file = await StorageFile.GetFileFromApplicationUriAsync(
                new Uri($"ms-appx:///Assets/Licenses/{name}"));
            text = await FileIO.ReadTextAsync(file);
            Read[name] = text;
        }

        // In a Regex replacement, "$" is a group reference. A holder's name is not a pattern, so each "$"
        // is escaped.
        return copyright is { Length: > 0 }
            ? Placeholder().Replace(text, copyright.Replace("$", "$$"), 1)
            : PlaceholderLine().Replace(text, string.Empty, 1);
    }

    /// <summary>The placeholder copyright line, from "Copyright (c) &lt;" to the end of its line. It does
    /// not include the line break, so the blank line under it stays when the line is filled in.</summary>
    [GeneratedRegex(@"^Copyright \(c\) <[^\n]*", RegexOptions.Multiline)]
    private static partial Regex Placeholder();

    /// <summary>The same line, with the line break after it, and the blank line under it when there is one.
    /// It is used when nothing replaces the line. The text then closes the gap, and does not start with two
    /// blank lines.</summary>
    [GeneratedRegex(@"^Copyright \(c\) <[^\n]*\n\n?", RegexOptions.Multiline)]
    private static partial Regex PlaceholderLine();
}
