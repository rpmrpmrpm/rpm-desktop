"""Records what the model said about a real track, and what the reference made of it.

The C# test replays these exact numbers through its own decoder and must arrive at the same beats.
This separates two questions: whether the C# code runs the model correctly, and whether it turns
the model's output into beats correctly. This fixture answers the second one, by comparing with
the reference implementation itself.
"""

import subprocess
import sys

import numpy as np
import onnxruntime as ort
import torch

from beat_this.inference import aggregate_prediction, split_piece
from beat_this.model.postprocessor import Postprocessor
from beat_this.preprocessing import LogMelSpect

SR, CHUNK, BORDER = 22050, 1500, 6
path = sys.argv[1]
seconds = 60

raw = subprocess.run(
    ["ffmpeg", "-v", "quiet", "-i", path, "-t", str(seconds), "-f", "f32le", "-ac", "1",
     "-ar", str(SR), "-"], capture_output=True, check=True).stdout
wave = torch.tensor(np.frombuffer(raw, dtype=np.float32).copy())

spect = LogMelSpect()(wave)
chunks, starts = split_piece(spect, CHUNK, border_size=BORDER, avoid_short_end=True)

session = ort.InferenceSession("RPM.Desktop/Assets/OnnxModels/beat_this.onnx",
                               providers=["CPUExecutionProvider"])
preds = []
for chunk in chunks:
    beat, downbeat = session.run(None, {"spect": chunk.unsqueeze(0).numpy()})
    preds.append({"beat": torch.tensor(beat[0]), "downbeat": torch.tensor(downbeat[0])})

bl, dl = aggregate_prediction(preds, starts, len(spect), CHUNK, BORDER, "keep_first", "cpu")
beats, downbeats = Postprocessor(type="minimal", fps=50)(bl.unsqueeze(0), dl.unsqueeze(0), None)
beats, downbeats = beats[0], downbeats[0]

lines = [
    "# Recorded from beat_this.onnx over the first 60s of a real track, with the beats and bar",
    "# lines the reference implementation derived from these same numbers. Replayed by",
    "# BeatModelDecoderTests. Generated by scripts/make_decoder_reference.py.",
    f"frames {len(spect)}",
    "starts " + " ".join(str(int(s)) for s in starts),
    "beats " + " ".join(f"{t:.4f}" for t in beats),
    "downbeats " + " ".join(f"{t:.4f}" for t in downbeats),
]
for n, (start, pred) in enumerate(zip(starts, preds)):
    lines.append(f"chunk {n} beat " + " ".join(f"{v:.4f}" for v in pred["beat"].numpy()))
    lines.append(f"chunk {n} downbeat " + " ".join(f"{v:.4f}" for v in pred["downbeat"].numpy()))

with open("RPM.Core.Tests/Assets/beat-decoder-reference.txt", "w") as f:
    f.write("\n".join(lines) + "\n")

print(f"frames {len(spect)}, windows {list(map(int, starts))}")
print(f"reference found {len(beats)} beats, {len(downbeats)} downbeats")
print("wrote RPM.Core.Tests/Assets/beat-decoder-reference.txt")
