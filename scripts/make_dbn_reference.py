"""Records what madmom's beat DBN makes of a set of curves, so the C# port can be tested against it.

BeatDbn is a port of madmom's DBNBeatTrackingProcessor. A port of a Viterbi search can run, produce
plausible beats and still be wrong. Reading it against the paper does not settle this: the state
space, the transition weights, the observation split and the place where the initial distribution is
applied can each be off by one and give a different answer.

So the reference decides. Each case below is a curve of per-frame logits built here, run through
madmom, and written out with the beats that madmom found. BeatDbnTests replays the same numbers and
must arrive at the same beats.

The cases are chosen for the failure modes that matter, not for coverage: a clean record, one where
the model marks the same beat twice (which breaks a simple peak picker), one where it misses beats
entirely, one that drifts, and one slow enough to sit at the top of the state space, where an
integer division in the observation model would lose a state.

    scripts/make_dbn_reference.py > RPM.Core.Tests/Assets/dbn-reference.txt

Needs madmom, which needs an old Python. This setup works:

    uv venv --python 3.10 mm
    uv pip install -p mm/bin/python "numpy<1.24" cython setuptools
    uv pip install -p mm/bin/python --no-build-isolation "madmom @ git+https://github.com/CPJKU/madmom.git"
"""

import numpy as np
from madmom.features.beats import DBNBeatTrackingProcessor

FPS = 50
MIN_BPM, MAX_BPM, TRANSITION_LAMBDA = 55.0, 215.0, 100

# Logit values for "this frame is a beat" and "this frame is not". They are not saturated on
# purpose: a curve of plus and minus infinity would give the same result whatever the observation
# model did with it.
ON, OFF = 4.0, -4.0


def clicks(seconds, bpm, drop=(), double=(), drift=0.0):
    """Returns a curve with a peak, one frame wide, on every beat.

    drop:   beat numbers the model missed entirely.
    double: beat numbers the model marked twice, the second peak three frames later. Three
            frames is 60 ms, which is a gap that madmom's own peak picker does not close.
    drift:  fraction the tempo speeds up over the whole excerpt.
    """
    frames = int(seconds * FPS)
    curve = np.full(frames, OFF, dtype=np.float64)

    at, beat, period = 0.0, 0, 60.0 * FPS / bpm
    while at < frames:
        if beat not in drop:
            curve[int(round(at))] = ON
            if beat in double and int(round(at)) + 3 < frames:
                curve[int(round(at)) + 3] = ON
        beat += 1
        at += period * (1 - drift * at / frames)

    return curve


def noise(seconds, seed):
    """Returns a curve with no music in it. The search still has to return something finite."""
    rng = np.random.default_rng(seed)
    return rng.normal(-2.0, 1.5, int(seconds * FPS))


CASES = {
    "clean_128": clicks(20, 128),
    "clean_60": clicks(20, 60),
    "clean_200": clicks(20, 200),
    "doubled_128": clicks(20, 128, double=range(0, 100, 2)),
    "doubled_every_beat_140": clicks(20, 140, double=range(0, 100)),
    "dropped_128": clicks(20, 128, drop=(4, 5, 12, 20, 21, 22)),
    "dropped_and_doubled_174": clicks(20, 174, drop=(7, 8, 9), double=(2, 3, 15)),
    "drifting_128": clicks(20, 128, drift=0.08),
    "noise": noise(20, 7),
}

dbn = DBNBeatTrackingProcessor(
    min_bpm=MIN_BPM, max_bpm=MAX_BPM, fps=FPS, transition_lambda=TRANSITION_LAMBDA)

print("# What madmom's DBNBeatTrackingProcessor made of each curve. Replayed by BeatDbnTests.")
print(f"# Generated by scripts/make_dbn_reference.py against madmom, "
      f"min_bpm={MIN_BPM} max_bpm={MAX_BPM} fps={FPS} transition_lambda={TRANSITION_LAMBDA}.")
print(f"states {dbn.st.num_states}")

def fingerprint(path):
    """Returns an FNV-1a hash over the path's states, so that the whole path is checked without
    writing it all out.

    The beats alone do not fix the search: two different paths can put the beats in the same places.
    A port that agrees on the beats but not on the path has a bug that another record will show.
    About 60,000 state numbers per case are too many to commit, but a hash of them is small.
    """
    value = 0xCBF29CE484222325
    for state in path:
        for byte in int(state).to_bytes(4, "little"):
            value = ((value ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return value


for name, logits in CASES.items():
    activations = 1 / (1 + np.exp(-logits))
    beats = dbn(activations)
    path, _ = dbn.hmm.viterbi(activations)

    print(f"case {name}")
    print("logits " + " ".join(f"{v:.4f}" for v in logits))
    print("beats " + " ".join(f"{b:.4f}" for b in beats))
    print(f"path {fingerprint(path)}")
